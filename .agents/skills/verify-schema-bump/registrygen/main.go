// Command registrygen writes roundtrip/registry_gen_test.go: a map from each
// schema $defs name that the SDK declares as a Go type to a constructor of
// that type. The generator names a def that only the unstable schema has
// Unstable<def>. Go cannot look a type up by name at run time, and the set of
// types changes with every schema version, so scripts/g2-roundtrip runs this
// before the test. The output is not committed.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	sdk := flag.String("sdk", "../../..", "SDK checkout root")
	out := flag.String("out", "roundtrip/registry_gen_test.go", "output file")
	flag.Parse()

	defs := map[string]bool{}
	for _, name := range []string{"schema.json", "schema.unstable.json"} {
		b, err := os.ReadFile(filepath.Join(*sdk, "schema", name))
		if err != nil {
			fatal(err)
		}
		var doc struct {
			Defs map[string]json.RawMessage `json:"$defs"`
		}
		if err := json.Unmarshal(b, &doc); err != nil {
			fatal(fmt.Errorf("%s: %w", name, err))
		}
		for d := range doc.Defs {
			defs[d] = true
		}
	}

	paths, err := filepath.Glob(filepath.Join(*sdk, "*.go"))
	if err != nil {
		fatal(err)
	}
	fset := token.NewFileSet()
	types := map[string]string{} // def -> Go type
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			fatal(err)
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				name := ts.Name.Name
				def := strings.TrimPrefix(name, "Unstable")
				if ts.TypeParams != nil || !defs[def] || (def != name && types[def] == def) {
					continue
				}
				types[def] = name
			}
		}
	}
	names := make([]string, 0, len(types))
	for def := range types {
		names = append(names, def)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by registrygen; DO NOT EDIT.\n\npackage roundtrip\n\n")
	buf.WriteString("import acp \"github.com/coder/acp-go-sdk\"\n\n")
	buf.WriteString("// registry maps a schema $defs name to a new value of its SDK Go type.\n")
	buf.WriteString("var registry = map[string]func() any{\n")
	for _, def := range names {
		fmt.Fprintf(&buf, "\t%q: func() any { return new(acp.%s) },\n", def, types[def])
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("registrygen: %d of %d schema defs have an SDK type\n", len(types), len(defs))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "registrygen:", err)
	os.Exit(2)
}
