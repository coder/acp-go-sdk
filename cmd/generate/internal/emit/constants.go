package emit

import (
	"bytes"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/coder/acp-go-sdk/cmd/generate/internal/load"
	"github.com/coder/acp-go-sdk/cmd/generate/internal/util"
)

// WriteConstantsJen writes the version and method constants to constants_gen.go.
// schemaVersion is the ACP schema release that meta comes from.
func WriteConstantsJen(outDir string, meta *load.Meta, schemaVersion string) error {
	f := NewFile("acp")
	f.HeaderComment("Code generated by acp-go-generator; DO NOT EDIT.")
	f.Comment("ProtocolVersionNumber is the ACP protocol version supported by this SDK.")
	f.Const().Id("ProtocolVersionNumber").Op("=").Lit(meta.Version)
	f.Comment("SchemaVersion is the ACP schema release that this SDK's generated code targets.")
	f.Const().Id("SchemaVersion").Op("=").Lit(schemaVersion)

	// One const block of wire method names per meta method map, in sorted key order.
	groups := []struct {
		prefix, comment string
		methods         map[string]string
	}{
		{"AgentMethod", "Agent method names", meta.AgentMethods},
		{"ClientMethod", "Client method names", meta.ClientMethods},
		{"ProtocolMethod", "Protocol method names, which either side can send", meta.ProtocolMethods},
	}
	for _, g := range groups {
		if len(g.methods) == 0 {
			continue
		}
		keys := make([]string, 0, len(g.methods))
		for k := range g.methods {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var defs []Code
		for _, k := range keys {
			defs = append(defs, Id(g.prefix+toExportedConst(k)).Op("=").Lit(g.methods[k]))
		}
		f.Comment(g.comment)
		f.Const().Defs(defs...)
	}

	var buf bytes.Buffer
	if err := f.Render(&buf); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "constants_gen.go"), buf.Bytes(), 0o644)
}

// Helpers kept private to this package (copy from original main)
func toExportedConst(s string) string {
	parts := strings.Split(s, "_")
	for i := range parts {
		parts[i] = util.TitleWord(parts[i])
	}
	return strings.Join(parts, "")
}
