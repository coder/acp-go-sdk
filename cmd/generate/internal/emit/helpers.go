// WriteHelpersJen emits go/helpers_gen.go with New<Union><Variant>
// constructors for the variants of oneOf unions. A variant that is a union in
// turn gets one New<Union><Variant><Alternative> constructor per alternative,
// because it encodes only with one of them set. It returns the error of
// schema.RefLoop, since the walkers of buildTypesJen would not return.
func WriteHelpersJen(outDir string, schema *load.Schema, meta *load.Meta) error {
	if err := schema.RefLoop(); err != nil {
		return err
	}
	f := NewFile("acp")
	f.HeaderComment("Code generated by acp-go-generator; DO NOT EDIT.")

	// Build the types once and take each union's variants exactly as emitUnion
	// emitted and named them, so every constructor builds a type that exists.
	_, emitted := buildTypesJen(schema, meta)

	// Iterate definitions deterministically
	keys := make([]string, 0, len(schema.Defs))
	for k := range schema.Defs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, name := range keys {
		def := schema.Defs[name]
		if def == nil || def.DocsIgnore || len(def.OneOf) == 0 {
			continue
		}
		// Skip string-const unions
		if isStringConstUnion(def) {
			continue
		}
		// Skip generating New... helpers for unions that have stable, static helpers
		// implemented in go/helpers.go.
		switch name {
		case "ContentBlock", "ToolCallContent", "SessionUpdate":
			continue
		}
		for _, vi := range emitted[name] {
			if len(vi.nested) == 0 {
				emitConstructor(f, name, vi, nil)
			}
			for i := range vi.nested {
				emitConstructor(f, name, vi, &vi.nested[i])
			}
		}
	}

	var buf bytes.Buffer
	if err := f.Render(&buf); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "helpers_gen.go"), buf.Bytes(), 0o644)
}

// requiredParams returns one parameter and one struct literal entry per
// required property of v, except its const discriminator, which gets its value.
func requiredParams(v unionVariant) ([]Code, Dict) {
	params := []Code{}
	assigns := Dict{}
	for _, key := range v.required {
		prop := v.props[key]
		if key == v.discKey || prop == nil {
			continue
		}
		params = append(params, Id(key).Add(jenTypeFor(prop)))
		assigns[Id(util.ToExportedField(key))] = Id(key)
	}
	if v.discKey != "" && v.discValue != "" {
		assigns[Id(util.ToExportedField(v.discKey))] = Lit(v.discValue)
	}
	return params, assigns
}

// variantPointer returns the parameter that a constructor takes for the value
// of v, the statement that declares the value, and a pointer to the value.
// For a struct v, the pointer is to a literal of assigns. A v that takes one
// value has no parameter.
func variantPointer(v unionVariant, assigns Dict) (param, decl []Code, pointer Code) {
	switch {
	case v.isStruct:
		return nil, nil, Op("&").Id(v.typeName).Values(assigns)
	case v.value != nil:
		return nil, []Code{Id("value").Op(":=").Id(v.typeName).Call(v.value)}, Op("&").Id("value")
	default:
		return []Code{Id("value").Id(v.typeName)}, nil, Op("&").Id("value")
	}
}

func emitConstructor(f *File, union string, v unionVariant, alternative *unionVariant) {
	params, assigns := requiredParams(v)
	var body []Code
	funcName := "New" + union + v.fieldName
	doc := fmt.Sprintf("%s constructs a %s using the '%s' variant.", funcName, union, v.discValue)
	if alternative != nil {
		alternativeParams, alternativeAssigns := requiredParams(*alternative)
		param, decl, pointer := variantPointer(*alternative, alternativeAssigns)
		params = append(append(params, alternativeParams...), param...)
		body = append(body, decl...)
		assigns[Id(alternative.fieldName)] = pointer
		funcName += alternative.fieldName
		doc = fmt.Sprintf("%s constructs a %s using the '%s' variant with its %s alternative.", funcName, union, v.discValue, alternative.fieldName)
	}
	param, decl, pointer := variantPointer(v, assigns)
	params = append(params, param...)
	body = append(body, decl...)
	f.Comment(doc)
	f.Func().Id(funcName).Params(params...).Id(union).Block(
		append(body, Return(Id(union).Values(Dict{Id(v.fieldName): pointer})))...,
	)
	f.Line()
}
