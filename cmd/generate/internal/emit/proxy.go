// WriteProxyJen writes proxy_gen.go: the handler structs of the proxy role,
// the dispatch of UnstableProxySideConnection, and the methods of its
// handles UnstableProxyClient and UnstableProxySuccessor. When meta lists no
// proxy methods, it writes nothing and removes a stale proxy_gen.go.
func WriteProxyJen(outDir string, schema *load.Schema, meta *load.Meta) error {
	path := filepath.Join(outDir, "proxy_gen.go")
	role, err := ir.BuildProxyRole(ir.BuildMethodGroups(schema, meta), meta)
	if err != nil {
		return err
	}
	if role == nil {
		if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		return nil
	}
	p := proxyEmitter{f: NewFile("acp"), schema: schema, role: role, consts: methodConsts(meta)}
	p.f.HeaderComment("Code generated by acp-go-generator; DO NOT EDIT.")
	p.handlerStruct("UnstableProxyFromClient", role.FromClient, "UnstableProxyFromClient holds a proxy's handlers for the messages from the\n"+
		"client side, which arrive as they are. A nil handler forwards its message to\n"+
		"the successor unchanged.")
	p.handlerStruct("UnstableProxyFromSuccessor", role.Client, "UnstableProxyFromSuccessor holds a proxy's handlers for the messages from its\n"+
		fmt.Sprintf("successor, which arrive wrapped in %s. A nil handler forwards its\n", role.Successor.Method)+
		"message to the client unchanged.")
	p.handle()
	p.handleFromSuccessor()
	p.clientMethods()
	p.successorMethods()
	var buf bytes.Buffer
	if err := p.f.Render(&buf); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

type proxyEmitter struct {
	f      *File
	schema *load.Schema
	role   *ir.ProxyRole
	// consts maps side|wire to the name of the method's constant.
	consts map[string]string
}

// methodConsts returns the names of the method constants of
// WriteConstantsJen, keyed by side|wire.
func methodConsts(meta *load.Meta) map[string]string {
	consts := map[string]string{}
	for _, g := range []struct {
		side, prefix string
		methods      map[string]string
	}{
		{"agent", "AgentMethod", meta.AgentMethods},
		{"client", "ClientMethod", meta.ClientMethods},
		{"proxy", "ProxyMethod", meta.ProxyMethods},
	} {
		for k, wire := range g.methods {
			consts[g.side+"|"+wire] = g.prefix + toExportedConst(k)
		}
	}
	return consts
}

func (p *proxyEmitter) constOf(mi *ir.MethodInfo) *Statement {
	return Id(p.consts[mi.Side+"|"+mi.Method])
}

// handlerStruct declares the struct name, with the doc comment doc, and one
// func field per method, named and typed as the Go method that handles it.
func (p *proxyEmitter) handlerStruct(name string, methods []*ir.MethodInfo, doc string) {
	emitDocComment(p.f, doc+" A handler runs only for a message of its kind:\n"+
		"a request for a request method, a notification for a notification method.\n\n"+
		"UNSTABLE: proxy chains are not part of the spec yet.")
	var fields []Code
	for _, mi := range methods {
		fields = appendDocComments(fields, methodDescription(p.schema, mi))
		if mi == p.role.Initialize {
			replaces := p.role.Replaces
			fields = appendDocComments(fields, fmt.Sprintf("\nA nil %s forwards the params to the successor as %s\n"+
				"and answers with the result. A handler must send %s to the successor, as\n"+
				"Successor().%s does, before it answers, and must not change protocolVersion.",
				mi.Name, replaces.Method, replaces.Method, replaces.Name))
		}
		fields = append(fields, methodSignature(p.schema, mi, Id(mi.Name).Func()))
	}
	p.f.Type().Id(name).Struct(fields...)
}

// typedCall decodes params as the message of mi, calls its handler h.<Name>,
// and returns the result, when the handler is set and the message is of
// mi's kind.
func (p *proxyEmitter) typedCall(mi *ir.MethodInfo) Code {
	handles := Id("h").Dot(mi.Name).Op("!=").Nil().Op("&&")
	if mi.Notif != "" {
		return If(handles.Id("notification")).Block(append(jUnmarshalValidate(mi.Notif), jCallNotification("h", mi.Name)...)...)
	}
	call := jCallRequestNoResp("h", mi.Name)
	if _, ok := responseType(p.schema, mi); ok {
		call = jCallRequestWithResp("h", mi.Name)
	}
	return If(handles.Op("!").Id("notification")).Block(append(jUnmarshalValidate(mi.Req), call...)...)
}

// unwrap returns the call of handleFromSuccessor with the decoded envelope p.
func unwrap(notification bool) Code {
	return Return(Id("c").Dot("handleFromSuccessor").Call(Id("ctx"), Id("p").Dot("Method"), Id("p").Dot("Params"), Lit(notification)))
}

// handle dispatches each message from the conductor.
func (p *proxyEmitter) handle() {
	role := p.role
	successor := []Code{If(Id("notification")).Block(append(jUnmarshalValidate(role.Successor.Notif), unwrap(true))...)}
	successor = append(successor, jUnmarshalValidate(role.Successor.Req)...)
	successor = append(successor, unwrap(false))
	rejection := fmt.Sprintf("proxies must be initialized with %s", role.Initialize.Method)
	cases := []Code{
		Case(p.constOf(role.Initialize)).Block(
			p.typedCall(role.Initialize),
			Return(Id("c").Dot("forwardToSuccessor").Call(Id("ctx"), p.constOf(role.Replaces), Id("params"), Id("notification"))),
		),
		Case(p.constOf(role.Successor)).Block(successor...),
		Case(p.constOf(role.Replaces)).Block(
			Return(Nil(), Id("NewInvalidRequest").Call(Map(String()).String().Values(Dict{Lit("error"): Lit(rejection)}))),
		),
	}
	for _, mi := range role.FromClient[1:] {
		cases = append(cases, Case(p.constOf(mi)).Block(p.typedCall(mi)))
	}
	p.f.Comment("handle dispatches a message from the conductor. A message from the client side")
	p.f.Comment("without a handler of its kind goes to the successor unchanged.")
	p.f.Func().Params(Id("c").Op("*").Id("UnstableProxySideConnection")).Id("handle").
		Params(Id("ctx").Qual("context", "Context"), Id("method").String(), Id("params").Qual("encoding/json", "RawMessage")).
		Params(Any(), Op("*").Id("RequestError")).
		Block(
			Id("h").Op(":=").Id("c").Dot("handlers").Dot("FromClient"),
			Id("notification").Op(":=").Id("c").Dot("isNotification").Call(Id("ctx")),
			Switch(Id("method")).Block(cases...),
			Return(Id("c").Dot("forwardToSuccessor").Call(Id("ctx"), Id("method"), Id("params"), Id("notification"))),
		)
}

// handleFromSuccessor dispatches the message in a proxy/successor envelope.
func (p *proxyEmitter) handleFromSuccessor() {
	var cases []Code
	for _, mi := range p.role.Client {
		cases = append(cases, Case(p.constOf(mi)).Block(p.typedCall(mi)))
	}
	p.f.Comment("handleFromSuccessor dispatches the message that a proxy/successor envelope from the")
	p.f.Comment("conductor carries. A message without a handler of its kind goes to the client unchanged.")
	p.f.Func().Params(Id("c").Op("*").Id("UnstableProxySideConnection")).Id("handleFromSuccessor").
		Params(Id("ctx").Qual("context", "Context"), Id("method").String(), Id("params").Qual("encoding/json", "RawMessage"), Id("notification").Bool()).
		Params(Any(), Op("*").Id("RequestError")).
		Block(
			Id("h").Op(":=").Id("c").Dot("handlers").Dot("FromSuccessor"),
			Switch(Id("method")).Block(cases...),
			Return(Id("c").Dot("forwardToClient").Call(Id("ctx"), Id("method"), Id("params"), Id("notification"))),
		)
}

// clientMethods declares a method of UnstableProxyClient per client method,
// which sends it to the client as it is.
func (p *proxyEmitter) clientMethods() {
	for _, mi := range p.role.Client {
		args := []Code{Id("ctx"), p.constOf(mi), Id("params")}
		var body Code
		switch resp, hasResp := responseType(p.schema, mi); {
		case mi.Notif != "":
			body = Return(Id("c").Dot("conn").Dot("SendNotification").Call(args...))
		case hasResp:
			body = Return(Id("SendRequest").Types(Id(resp)).Call(append([]Code{Id("c").Dot("conn")}, args...)...))
		default:
			body = Return(Id("c").Dot("conn").Dot("SendRequestNoResult").Call(args...))
		}
		p.f.Comment(fmt.Sprintf("%s sends %s to the client.", mi.Name, mi.Method))
		methodSignature(p.schema, mi, p.f.Func().Params(Id("c").Op("*").Id("UnstableProxyClient")).Id(mi.Name)).Block(body)
	}
}

// successorMethods declares a method of UnstableProxySuccessor per agent
// method, which sends it to the successor in a proxy/successor envelope.
func (p *proxyEmitter) successorMethods() {
	for _, mi := range p.role.Agent {
		args := []Code{Id("s"), Id("ctx"), p.constOf(mi), Id("params")}
		var body []Code
		switch resp, hasResp := responseType(p.schema, mi); {
		case mi.Notif != "":
			body = []Code{Return(Id("s").Dot("notify").Call(args[1:]...))}
		case hasResp:
			body = []Code{Return(Id("successorRequest").Types(Id(resp)).Call(args...))}
		default:
			body = []Code{
				List(Id("_"), Id("err")).Op(":=").Id("successorRequest").Types(rawJSON()).Call(args...),
				Return(Id("err")),
			}
		}
		p.f.Comment(fmt.Sprintf("%s sends %s to the successor, wrapped in %s.", mi.Name, mi.Method, p.role.Successor.Method))
		methodSignature(p.schema, mi, p.f.Func().Params(Id("s").Op("*").Id("UnstableProxySuccessor")).Id(mi.Name)).Block(body...)
	}
}
